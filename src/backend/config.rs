#[derive(Error, Debug, Clone)]
pub enum ConfigError {
    #[error("Missing [Interface] section")]
    MissingInterfaceSection,
    #[error("Missing [Peer] section")]
    MissingPeerSection,
    #[error("Missing required field '{0}' in [Interface]")]
    MissingInterfaceField(String),
    #[error("Missing required field '{0}' in [Peer]")]
    MissingPeerField(String),
    #[error("Invalid WireGuard key: {0}")]
    InvalidKey(String),
    #[error("Invalid IP/CIDR address: {0}")]
    InvalidAddress(String),
    #[error("Invalid endpoint format: {0}. Expected host:port")]
    InvalidEndpoint(String),
    #[error("File error: {0}")]
    IoError(String),
    #[error("Parse error at line {0}: {1}")]
    SyntaxError(usize, String),
}

/// Represents the `[Interface]` section of a WireGuard configuration.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct InterfaceConfig {
    /// Base64-encoded WireGuard client private key (32 bytes / 44 chars)
    pub private_key: String,
    /// IP addresses assigned to the tunnel interface (e.g. ["10.13.1.2/32"])
    pub address: Vec<String>,
    /// DNS servers (e.g. ["10.13.1.1", "1.1.1.1"])
    pub dns: Vec<String>,
    /// Optional MTU (e.g. 1420)
    pub mtu: Option<u16>,
    /// Optional custom listen port
    pub listen_port: Option<u16>,
    /// Pre-up commands
    pub pre_up: Vec<String>,
    /// Post-up commands
    pub post_up: Vec<String>,
    /// Pre-down commands
    pub pre_down: Vec<String>,
    /// Post-down commands
    pub post_down: Vec<String>,
}

impl Default for InterfaceConfig {
    fn default() -> Self {
        Self {
            private_key: String::new(),
            address: Vec::new(),
            dns: vec!["1.1.1.1".to_string(), "1.0.0.1".to_string()],
            mtu: Some(1420),
            listen_port: None,
            pre_up: Vec::new(),
            post_up: Vec::new(),
            pre_down: Vec::new(),
            post_down: Vec::new(),
        }
    }
}

/// Represents the `[Peer]` section of a WireGuard configuration.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PeerConfig {
    /// Base64-encoded FastestVPN server public key
    pub public_key: String,
    /// Optional preshared key
    pub preshared_key: Option<String>,
    /// Endpoint address: host/IP and port (e.g. "de-01.jumptoserver.com:51820")
    pub endpoint: String,
    /// Routed IPs (default "0.0.0.0/0, ::/0" for full tunnel)
    pub allowed_ips: Vec<String>,
    /// Persistent keepalive interval in seconds (default 25)
    pub persistent_keepalive: Option<u16>,
}

impl Default for PeerConfig {
    fn default() -> Self {
        Self {
            public_key: String::new(),
            preshared_key: None,
            endpoint: String::new(),
            allowed_ips: vec!["0.0.0.0/0".to_string(), "::/0".to_string()],
            persistent_keepalive: Some(25),
        }
    }
}

/// Full WireGuard configuration profile.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, Default)]
pub struct WireGuardConfig {
    pub interface: InterfaceConfig,
    pub peer: PeerConfig,
}

impl WireGuardConfig {
    /// Validate keys, addresses, and endpoints.
    pub fn validate(&self) -> Result<(), ConfigError> {
        // Validate private key format (FastestVPN / WireGuard uses standard base64 32 bytes)
        validate_wireguard_key(&self.interface.private_key)
            .map_err(|e| ConfigError::InvalidKey(format!("Interface PrivateKey: {e}")))?;

        // Validate peer public key format
        validate_wireguard_key(&self.peer.public_key)
            .map_err(|e| ConfigError::InvalidKey(format!("Peer PublicKey: {e}")))?;

        if self.interface.address.is_empty() {
            return Err(ConfigError::MissingInterfaceField("Address".to_string()));
        }

        if self.peer.endpoint.trim().is_empty() {
            return Err(ConfigError::MissingPeerField("Endpoint".to_string()));
        }

        // Validate endpoint structure
        if !self.peer.endpoint.contains(':') {
            return Err(ConfigError::InvalidEndpoint(self.peer.endpoint.clone()));
        }

        Ok(())
    }

    /// Serializes configuration into WireGuard standard `.conf` INI format.
    pub fn to_conf_string(&self) -> String {
        let mut out = String::new();
        out.push_str("# Generated by FastestVPN Linux Desktop Client\n");
        out.push_str("[Interface]\n");
        out.push_str(&format!("PrivateKey = {}\n", self.interface.private_key.trim()));
        if !self.interface.address.is_empty() {
            out.push_str(&format!("Address = {}\n", self.interface.address.join(", ")));
        }
        if !self.interface.dns.is_empty() {
            out.push_str(&format!("DNS = {}\n", self.interface.dns.join(", ")));
        }
        if let Some(mtu) = self.interface.mtu {
            out.push_str(&format!("MTU = {}\n", mtu));
        }
        if let Some(port) = self.interface.listen_port {
            out.push_str(&format!("ListenPort = {}\n", port));
        }
        for cmd in &self.interface.pre_up {
            out.push_str(&format!("PreUp = {}\n", cmd));
        }
        for cmd in &self.interface.post_up {
            out.push_str(&format!("PostUp = {}\n", cmd));
        }
        for cmd in &self.interface.pre_down {
            out.push_str(&format!("PreDown = {}\n", cmd));
        }
        for cmd in &self.interface.post_down {
            out.push_str(&format!("PostDown = {}\n", cmd));
        }

        out.push_str("\n[Peer]\n");
        out.push_str(&format!("PublicKey = {}\n", self.peer.public_key.trim()));
        if let Some(ref psk) = self.peer.preshared_key {
            if !psk.trim().is_empty() {
                out.push_str(&format!("PresharedKey = {}\n", psk.trim()));
            }
        }
        out.push_str(&format!("Endpoint = {}\n", self.peer.endpoint.trim()));
        let allowed = if self.peer.allowed_ips.is_empty() {
            "0.0.0.0/0, ::/0".to_string()
        } else {
            self.peer.allowed_ips.join(", ")
        };
        out.push_str(&format!("AllowedIPs = {}\n", allowed));
        if let Some(ka) = self.peer.persistent_keepalive {
            out.push_str(&format!("PersistentKeepalive = {}\n", ka));
        }

        out
    }
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Default)]
pub enum VpnProtocol {
    #[default]
    WireGuard,
    OpenVpnUdp,
    OpenVpnTcp,
}

impl std::fmt::Display for VpnProtocol {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            VpnProtocol::WireGuard => write!(f, "WireGuard"),
            VpnProtocol::OpenVpnUdp => write!(f, "OpenVPN (UDP)"),
            VpnProtocol::OpenVpnTcp => write!(f, "OpenVPN (TCP)"),
        }
    }
}

/// Profile metadata with user-friendly country, city, protocol and identifier.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct VpnProfile {
    pub id: String,
    pub name: String,
    pub country: String,
    pub country_code: String,
    pub city: String,
    pub protocol: VpnProtocol,
    pub config: WireGuardConfig,
    pub file_path: Option<PathBuf>,
    pub is_preset: bool,
    pub ovpn_endpoint: Option<String>,
}

impl VpnProfile {
    pub fn new_custom(name: String, config: WireGuardConfig) -> Self {
        let (country, code, city) = infer_location(&name, &config.peer.endpoint);
        let id = format!("{}_{}", sanitize_id(&name), chrono::Utc::now().timestamp_millis());
        Self {
            id,
            name,
            country,
            country_code: code,
            city,
            protocol: VpnProtocol::WireGuard,
            config,
            file_path: None,
            is_preset: false,
            ovpn_endpoint: None,
        }
    }

    pub fn display_endpoint(&self) -> &str {
        if let Some(ref ep) = self.ovpn_endpoint {
            ep
        } else {
            &self.config.peer.endpoint
        }
    }
}

/// Validates base64 key string (32 bytes when decoded -> 44 chars with base64 padding)
fn validate_wireguard_key(key: &str) -> Result<(), &'static str> {
    let trimmed = key.trim();
    if trimmed.is_empty() {
        return Err("Key is empty");
    }
    if trimmed.len() != 44 {
        return Err("Key length must be exactly 44 base64 characters");
    }
    // Check characters
    for c in trimmed.chars() {
        if !c.is_ascii_alphanumeric() && c != '+' && c != '/' && c != '=' {
            return Err("Invalid base64 character in key");
        }
    }
    Ok(())
}

/// Parse a WireGuard `.conf` file content into `WireGuardConfig`.
pub fn parse_wireguard_conf(content: &str) -> Result<WireGuardConfig, ConfigError> {
    let mut current_section = "";
    let mut interface_map: HashMap<String, Vec<String>> = HashMap::new();
    let mut peer_map: HashMap<String, Vec<String>> = HashMap::new();

    for (line_idx, raw_line) in content.lines().enumerate() {
        let line = raw_line.trim();
        // Ignore empty lines and comments (# or ;)
        if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
            continue;
        }

        if line.starts_with('[') && line.ends_with(']') {
            let section_name = line[1..line.len() - 1].trim();
            if section_name.eq_ignore_ascii_case("Interface") {
                current_section = "Interface";
            } else if section_name.eq_ignore_ascii_case("Peer") {
                current_section = "Peer";
            } else {
                current_section = "Other";
            }
            continue;
        }

        if let Some((key, val)) = line.split_once('=') {
            let key = key.trim().to_ascii_lowercase();
            let val = val.trim().to_string();

            match current_section {
                "Interface" => {
                    interface_map.entry(key).or_default().push(val);
                }
                "Peer" => {
                    peer_map.entry(key).or_default().push(val);
                }
                _ => {}
            }
        } else {
            return Err(ConfigError::SyntaxError(
                line_idx + 1,
                format!("Expected 'Key = Value', got '{}'", line),
            ));
        }
    }

    if interface_map.is_empty() {
        return Err(ConfigError::MissingInterfaceSection);
    }
    if peer_map.is_empty() {
        return Err(ConfigError::MissingPeerSection);
    }

    // Extract Interface fields
    let private_key = interface_map
        .get("privatekey")
        .and_then(|v| v.first())
        .cloned()
        .ok_or_else(|| ConfigError::MissingInterfaceField("PrivateKey".to_string()))?;

    let address = interface_map
        .get("address")
        .map(|list| {
            list.iter()
                .flat_map(|s| s.split(','))
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
                .collect()
        })
        .unwrap_or_default();

    let dns = interface_map
        .get("dns")
        .map(|list| {
            list.iter()
                .flat_map(|s| s.split(','))
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
                .collect()
        })
        .unwrap_or_else(|| vec!["1.1.1.1".to_string(), "1.0.0.1".to_string()]);

    let mtu = interface_map
        .get("mtu")
        .and_then(|v| v.first())
        .and_then(|s| s.parse::<u16>().ok());

    let listen_port = interface_map
        .get("listenport")
        .and_then(|v| v.first())
        .and_then(|s| s.parse::<u16>().ok());

    let pre_up = interface_map.get("preup").cloned().unwrap_or_default();
    let post_up = interface_map.get("postup").cloned().unwrap_or_default();
    let pre_down = interface_map.get("predown").cloned().unwrap_or_default();
    let post_down = interface_map.get("postdown").cloned().unwrap_or_default();

    // Extract Peer fields
    let public_key = peer_map
        .get("publickey")
        .and_then(|v| v.first())
        .cloned()
        .ok_or_else(|| ConfigError::MissingPeerField("PublicKey".to_string()))?;

    let endpoint = peer_map
        .get("endpoint")
        .and_then(|v| v.first())
        .cloned()
        .ok_or_else(|| ConfigError::MissingPeerField("Endpoint".to_string()))?;

    let allowed_ips = peer_map
        .get("allowedips")
        .map(|list| {
            list.iter()
                .flat_map(|s| s.split(','))
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
                .collect()
        })
        .unwrap_or_else(|| vec!["0.0.0.0/0".to_string(), "::/0".to_string()]);

    let preshared_key = peer_map.get("presharedkey").and_then(|v| v.first()).cloned();

    let persistent_keepalive = peer_map
        .get("persistentkeepalive")
        .and_then(|v| v.first())
        .and_then(|s| s.parse::<u16>().ok());

    let config = WireGuardConfig {
        interface: InterfaceConfig {
            private_key,
            address,
            dns,
            mtu,
            listen_port,
            pre_up,
            post_up,
            pre_down,
            post_down,
        },
        peer: PeerConfig {
            public_key,
            preshared_key,
            endpoint,
            allowed_ips,
            persistent_keepalive,
        },
    };

    config.validate()?;
    Ok(config)
}

/// Reads and parses a `.conf` file into a `VpnProfile`.
pub fn load_profile_from_file(path: &Path) -> Result<VpnProfile, ConfigError> {
    let content = fs::read_to_string(path)
        .map_err(|e| ConfigError::IoError(format!("Could not read {:?}: {}", path, e)))?;

    let config = parse_wireguard_conf(&content)?;
    let file_stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("fastestvpn");

    let clean_name = format_profile_name(file_stem);
    let (country, code, city) = infer_location(&clean_name, &config.peer.endpoint);
    let id = sanitize_id(file_stem);

    Ok(VpnProfile {
        id,
        name: clean_name,
        country,
        country_code: code,
        city,
        protocol: VpnProtocol::WireGuard,
        config,
        file_path: Some(path.to_path_buf()),
        is_preset: false,
        ovpn_endpoint: None,
    })
}

/// Formats raw filenames like `germany-frankfurt-tcp` or `us-newyork` into "Germany Frankfurt".
fn format_profile_name(raw: &str) -> String {
    let cleaned = raw
        .replace("-tcp", "")
        .replace("-udp", "")
        .replace("-wireguard", "")
        .replace("_", " ")
        .replace("-", " ");

    cleaned
        .split_whitespace()
        .map(|word| {
            let mut c = word.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

