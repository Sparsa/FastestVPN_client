/// Generates a valid FastestVPN OpenVPN configuration (.ovpn) string.
pub fn generate_fastestvpn_ovpn(server_host: &str, protocol: VpnProtocol) -> String {
    let proto_str = match protocol {
        VpnProtocol::OpenVpnTcp => "tcp",
        _ => "udp",
    };

    let mut out = String::new();
    out.push_str("# Generated by FastestVPN Linux Desktop Client\n");
    out.push_str("client\n");
    out.push_str(&format!("remote {} {}\n", server_host, FASTESTVPN_PORT));
    out.push_str(&format!("proto {}\n", proto_str));
    out.push_str("dev tun\n");
    out.push_str("auth-user-pass\n");
    out.push_str("tls-client\n");
    out.push_str("resolv-retry infinite\n");
    out.push_str("remote-random\n");
    out.push_str("nobind\n");
    out.push_str("tun-mtu 1500\n");
    out.push_str("mssfix 1450\n");
    out.push_str("persist-key\n");
    out.push_str("persist-tun\n");
    out.push_str("ping 15\n");
    out.push_str("ping-restart 0\n");
    out.push_str("reneg-sec 0\n");
    out.push_str("comp-lzo\n");
    out.push_str("cipher AES-256-CBC\n");
    // OpenVPN >= 2.6 ignores `cipher` for negotiation; allow CBC for servers without NCP.
    out.push_str("data-ciphers AES-256-GCM:AES-128-GCM:AES-256-CBC\n");
    out.push_str("data-ciphers-fallback AES-256-CBC\n");
    out.push_str("auth SHA256\n");
    out.push_str("<ca>\n");
    out.push_str(FASTESTVPN_ROOT_CA);
    out.push_str("\n</ca>\n");
    out.push_str("key-direction 1\n");
    out.push_str("<tls-auth>\n");
    out.push_str(FASTESTVPN_TLS_AUTH);
    out.push_str("\n</tls-auth>\n");

    out
}

/// Parses an existing .ovpn file into a VpnProfile
pub fn load_ovpn_profile_from_file(path: &Path) -> Result<VpnProfile, String> {
    let content = fs::read_to_string(path).map_err(|e| e.to_string())?;

    let file_stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("fastestvpn_ovpn");

    let is_tcp = content.lines().any(|l| l.trim().starts_with("proto tcp"));
    let protocol = if is_tcp {
        VpnProtocol::OpenVpnTcp
    } else {
        VpnProtocol::OpenVpnUdp
    };

    // Find remote host: remote <host> <port>
    let mut endpoint = "de-01.jumptoserver.com:4443".to_string();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("remote ") {
            let parts: Vec<&str> = trimmed.split_whitespace().collect();
            if parts.len() >= 2 {
                let host = parts[1];
                let port = parts.get(2).unwrap_or(&"4443");
                endpoint = format!("{host}:{port}");
                break;
            }
        }
    }

    let clean_name = file_stem
        .replace("-tcp", "")
        .replace("-udp", "")
        .replace("_", " ")
        .replace("-", " ");

    let (country, code, city) = infer_location(&clean_name, &endpoint);

    let mut profile = VpnProfile::new_custom(clean_name, Default::default());
    // Imported files are stored as `<id>.ovpn`, so don't re-prefix on reload.
    let stem_id = sanitize_id(file_stem);
    profile.id = if stem_id.starts_with("ovpn_") {
        stem_id
    } else {
        format!("ovpn_{stem_id}")
    };
    profile.country = country;
    profile.country_code = code;
    profile.city = city;
    profile.protocol = protocol;
    profile.file_path = Some(path.to_path_buf());
    profile.ovpn_endpoint = Some(endpoint);

    Ok(profile)
}
